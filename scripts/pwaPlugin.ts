import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';
import { GAME_DESCRIPTION, GAME_NAME, SAVE_KEY_PREFIX, THEME_COLOR } from '../src/config.ts';
import { renderIcon } from './icons.ts';

type AppEnv = 'prod' | 'dev' | 'test';

function manifestJson(appName: string): string {
  return JSON.stringify(
    {
      id: '/',
      name: appName,
      short_name: appName,
      description: GAME_DESCRIPTION,
      start_url: '/',
      scope: '/',
      display: 'standalone',
      orientation: 'any',
      background_color: THEME_COLOR,
      theme_color: THEME_COLOR,
      icons: [
        { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      ],
    },
    null,
    2,
  );
}

/** Cache-first service worker. A new version waits until all tabs close (no mid-session code swaps). */
function serviceWorkerSource(cacheName: string, cachePrefix: string, assets: string[]): string {
  return `// generated by scripts/pwaPlugin.ts
const CACHE = ${JSON.stringify(cacheName)};
const PREFIX = ${JSON.stringify(cachePrefix)};
const ASSETS = ${JSON.stringify(assets)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(ASSETS.map((url) => new Request(url, { cache: 'reload' })))),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') void self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req).then((hit) => {
      if (hit) return hit;
      if (req.mode === 'navigate') return caches.match('/index.html').then((page) => page || fetch(req));
      return fetch(req);
    }),
  );
});
`;
}

export function pwaPlugin(appEnv: AppEnv): Plugin {
  const appName = appEnv === 'dev' ? `${GAME_NAME} DEV` : GAME_NAME;
  const withBadge = appEnv === 'dev';
  const staticFiles = (): Record<string, { type: string; body: string | Buffer }> => ({
    '/manifest.webmanifest': { type: 'application/manifest+json', body: manifestJson(appName) },
    '/icon-192.png': { type: 'image/png', body: renderIcon(192, withBadge) },
    '/icon-512.png': { type: 'image/png', body: renderIcon(512, withBadge) },
  });

  return {
    name: 'cyfil-pwa',
    transformIndexHtml: {
      order: 'pre',
      handler: (html) =>
        html
          .replaceAll('%APP_NAME%', appName)
          .replaceAll('%THEME_COLOR%', THEME_COLOR)
          .replaceAll('%GAME_DESCRIPTION%', GAME_DESCRIPTION),
    },
    configureServer(server) {
      const files = staticFiles();
      server.middlewares.use((req, res, next) => {
        const hit = req.url ? files[req.url.split('?')[0] ?? ''] : undefined;
        if (!hit) {
          next();
          return;
        }
        res.setHeader('Content-Type', hit.type);
        res.end(hit.body);
      });
    },
    generateBundle: {
      order: 'post',
      handler(_options, bundle) {
        const files = staticFiles();
        for (const [path, f] of Object.entries(files)) {
          this.emitFile({ type: 'asset', fileName: path.slice(1), source: f.body });
        }
        const assets = ['/', ...Object.keys(bundle).map((n) => `/${n}`), ...Object.keys(files)];
        const buildId = createHash('sha256').update([...assets].sort().join('\n')).digest('hex').slice(0, 10);
        this.emitFile({
          type: 'asset',
          fileName: 'sw.js',
          source: serviceWorkerSource(`${SAVE_KEY_PREFIX}-${appEnv}-${buildId}`, `${SAVE_KEY_PREFIX}-${appEnv}-`, assets),
        });
      },
    },
  };
}
